def load(name):
    with open(PROC / f"{name}.csv", newline="") as f:
        return list(csv.DictReader(f))


def f(r, k):
    return float(r[k]) if r[k] not in ("", None) else float("nan")


def agg(rows, key, col):
    g = defaultdict(list)
    for r in rows:
        g[key(r)].append(f(r, col))
    return {k: (st.median(v), min(v), max(v)) for k, v in g.items()}


def table(header, body, fmt="{:.1f}"):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for r in body:
        out.append("| " + " | ".join(x if isinstance(x, str) else fmt.format(x) for x in r) + " |")
    return out


def save(fig, name):
    fig.savefig(PLOTS / name, bbox_inches="tight")
    plt.close(fig)
    print("  plots/" + name)


def wcsv(name, header, body):
    with open(PROC / name, "w", newline="") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(header)
        w.writerows(body)


def d(rw):
    return "read" if "read" in rw else "write"


