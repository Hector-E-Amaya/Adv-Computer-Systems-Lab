"""Batch 3 analysis for the SSD project: tables and plots.

Inputs : data/processed/<sweep>.csv (scripts/parse_fio.py), data/raw/state/*.log
         (fio 1 s logs), data/raw/perf_log.csv (Windows disk/CPU counters)
Outputs: plots/*.png, data/processed/summary_*.csv, reports/RESULTS_TABLES.md

Statistics: each configuration ran 3 times (separate fio processes). Tables
report the median over the 3, with min..max as the spread / error band.
Latency = total (submission + completion) as fio's lat_ns; percentiles from
fio's lat percentiles (lat_percentiles=1).
"""
