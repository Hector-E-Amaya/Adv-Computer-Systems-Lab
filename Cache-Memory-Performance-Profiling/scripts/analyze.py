def tlb_ns(size):
    pages = size // 4096
    known = sorted(tlbcost)
    if pages <= known[0]:
        return 0.0
    if pages >= known[-1]:
        return tlbcost[known[-1]]
    for a, b in zip(known, known[1:]):
        if a <= pages <= b:
            fa, fb = tlbcost[a], tlbcost[b]
            return fa + (fb - fa) * (math.log(pages) - math.log(a)) / (math.log(b) - math.log(a))


def fracs(size_tag):
    """Fractions of loads per level, normalised by the sum of the four
    MEM_LOAD_RETIRED buckets. Normalising by instructions/2.5 (exact loads)
    gave >100% DRAM at 64-256 MB: with 7 programmable events VTune
    multiplexes counters and scales each event separately, which skews
    multi-phase runs. Fill-buffer hits (the missing 5th bucket) are
    negligible in a random dependent chase. The bucket-sum / exact-loads ratio
    is returned as a data-quality indicator."""
    t, _ = counters(f"lat_random_{size_tag}")
    b = [t[f"MEM_LOAD_RETIRED.{x}"] for x in ("L1_HIT", "L2_HIT", "L3_HIT", "L3_MISS")]
    return [x / sum(b) for x in b], sum(b) / (t["INST_RETIRED.ANY"] / 2.5)


tags = {"16K": 16 << 10, "64K": 64 << 10, "256K": 256 << 10, "1M": 1 << 20, "2M": 2 << 20, "4M": 4 << 20,
        "8M": 8 << 20, "16M": 16 << 20, "64M": 64 << 20, "256M": 256 << 20}
# t_L1 (16 KB) and t_L2 (128 KB, 32 pages: no TLB cost) are pure. Pure t_L3 and
# t_DRAM are solved from two calibration points (4 MB, 256 MB), removing their
# measured L1/L2 shares and TLB cost; taking t_L3 straight from the 4 MB
# latency would count its TLB cost twice. All other sizes are out-of-sample.
CAL = ("4M", "256M")
(fa, _), (fb_, _) = fracs(CAL[0]), fracs(CAL[1])
ra = lat[tags[CAL[0]]][0] - tlb_ns(tags[CAL[0]]) - fa[0] * t1 - fa[1] * t2
rb = lat[tags[CAL[1]]][0] - tlb_ns(tags[CAL[1]]) - fb_[0] * t1 - fb_[1] * t2
det = fa[2] * fb_[3] - fa[3] * fb_[2]
t3 = (ra * fb_[3] - fa[3] * rb) / det
tdram = (fa[2] * rb - ra * fb_[2]) / det
abody = []
for tag, size in tags.items():
    f, fb = fracs(tag)
    pred = f[0] * t1 + f[1] * t2 + f[2] * t3 + f[3] * tdram + tlb_ns(size)
    meas = lat[size][0]
    abody.append([tag, *(100 * x for x in f), fb, tlb_ns(size), pred, meas, 100 * (pred - meas) / meas,
                  "calibration" if tag in CAL or tag == "16K" else ""])
write_csv("amat.csv", ["size", "pct_L1", "pct_L2", "pct_L3", "pct_DRAM", "buckets_per_exact_load", "tlb_ns",
                       "amat_pred_ns", "measured_ns", "error_pct", "note"], abody)
md += ["## 7. AMAT reconstruction", "",
       f"AMAT = sum(f_level x t_level) + TLB(size). f = share of each MEM_LOAD_RETIRED bucket "
       f"(L1/L2/L3 hit, L3 miss) in the timed loop. t_L1 {t1:.2f} ns (16 KB) and t_L2 {t2:.2f} ns (128 KB) from "
       f"the zero-queue table; TLB(size) = page-mode minus control from section 2 (log-interpolated). Pure "
       f"t_L3 {t3:.2f} ns and t_DRAM {tdram:.1f} ns solved from the 4 MB and 256 MB calibration points. Every "
       f"other size is an out-of-sample prediction. Target (H5): within 15%.", ""]
md += table(["size", "% L1", "% L2", "% L3", "% DRAM", "buckets / exact loads", "TLB ns", "AMAT ns",
             "measured ns", "error %", "note"], abody, fmt="{:.2f}")
md += ["", "buckets / exact loads != 1 shows VTune multiplexing scale error (7 events > counters); "
           "fractions are therefore normalised within the buckets."]
md += [""]
fig, ax = plt.subplots(figsize=(7.5, 3.8))
sz = [tags[r[0]] for r in abody]
ax.plot(sz, [r[8] for r in abody], color=C[0], marker=M[0], label="measured")
ax.plot(sz, [r[7] for r in abody], color=C[1], marker=M[1], ls="--", label="AMAT prediction (counters)")
ax.set_xscale("log", base=2)
ax.set_yscale("log")
vlines(ax)
