def rows(name, d=RAW):
    with open(d / f"sweep_{name}.csv", newline="") as f:
        return list(csv.DictReader(f))


def agg(rs, key, val):
    g = defaultdict(list)
    for r in rs:
        g[key(r)].append(float(r[val]))
    return {k: (st.median(v), min(v), max(v)) for k, v in g.items()}


def save(fig, name):
    fig.savefig(PLOTS / name, bbox_inches="tight")
    plt.close(fig)
    print("  plots/" + name)


def table(header, body, fmt=None):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for r in body:
        out.append("| " + " | ".join(x if isinstance(x, str) else (fmt or "{:.2f}").format(x) for x in r) + " |")
    return out


def write_csv(name, header, body):
    with open(PROC / name, "w", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(header)
        w.writerows(body)


def vlines(ax, per_elem=1):
    for lab, cap in CACHES:
        x = cap / per_elem
